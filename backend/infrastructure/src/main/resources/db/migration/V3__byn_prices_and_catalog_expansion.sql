-- ---------- Цены в BYN ----------
-- Демонстрационные цены V2 были заданы в российских рублях: пересчёт по курсу ≈ 28 RUB за 1 BYN
-- с «магазинным» округлением до …,90.
UPDATE products SET price = ceil(price / 28) - 0.10;
UPDATE order_items SET price = ceil(price / 28) - 0.10;
UPDATE orders o
SET total_amount = (SELECT coalesce(sum(i.price * i.quantity), 0) FROM order_items i WHERE i.order_id = o.id);

-- ---------- Белорусские номера телефонов ----------
UPDATE users SET phone = '+37529' || lpad(right(regexp_replace(phone, '\D', '', 'g'), 7), 7, '0')
WHERE phone IS NOT NULL AND phone NOT LIKE '+375%';
UPDATE orders SET contact_phone = '+37529' || lpad(right(regexp_replace(contact_phone, '\D', '', 'g'), 7), 7, '0')
WHERE contact_phone NOT LIKE '+375%';

